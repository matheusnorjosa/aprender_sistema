import type { UFCode } from '@/types/organizacao';
import type { MeioDeslocamento } from './tipos';

/** Faixa de ida e volta: Próximo até 3h · Médio até 10h · Longo até 18h · Muito longo acima de 18h. */
export type FaixaDeslocamento = 'proximo' | 'medio' | 'longo' | 'muito_longo';

export interface MunicipioDeslocamento {
  nome: string;
  uf: UFCode;
  /** `carro` = só por terra; `aviao` = tem trecho aéreo (com carro ou barco no fim). */
  meio: MeioDeslocamento;
  /** Modal recomendado, como no PDF (ex.: "Aéreo + terrestre"). */
  modal: string;
  rota: string;
  /** Tempos de voo, conexão e trecho final (só quando vai de avião). */
  detalhe_rota: string | null;
  ida_horas: number;
  ida_texto: string;
  ida_volta_horas: number;
  ida_volta_texto: string;
  /** A faixa que o PDF escreve, com as correções do dono no roteiro (decisão 54: Craíbas-AL em Longo). */
  faixa: FaixaDeslocamento;
  /** O outro modal, só para comparação (ex.: "Terrestre: 27h05"). */
  alternativa: string | null;
  acoes_suspensas: boolean;
  travessia_maritima: boolean;
  terrestre_por_decisao_da_gestao: boolean;
}

export interface InfoFaixaDeslocamento {
  faixa: FaixaDeslocamento;
  rotulo: string;
  descricao: string;
  /** Limite de cima, em horas de ida e volta; `null` = sem limite (a última faixa). */
  ate_horas: number | null;
}

export interface RegraDoCalculo {
  componente: string;
  tempo: string;
  criterio: string;
}

export interface FiltroDeslocamento {
  uf?: UFCode;
  faixa?: FaixaDeslocamento;
  meio?: MeioDeslocamento;
}

/**
 * Decisão 55: o tempo do meio é a mediana que a página 1 do relatório escreve, 17h45 (17,75 h). O ICA usa
 * esse tempo, marcado como estimado, para o local que não está no relatório.
 */
export const TEMPO_DO_MEIO_HORAS = 17.75;

/** Mediana das horas de ida e volta (lista vazia = 0; lista par = média dos dois do meio). */
export function medianaIdaVolta(municipios: readonly MunicipioDeslocamento[]): number {
  const horas = municipios.map((m) => m.ida_volta_horas).sort((a, b) => a - b);
  if (horas.length === 0) return 0;
  const meio = Math.floor(horas.length / 2);
  const centro = horas[meio] ?? 0;
  return horas.length % 2 === 1 ? centro : ((horas[meio - 1] ?? 0) + centro) / 2;
}

export function contarPorFaixa(municipios: readonly MunicipioDeslocamento[]): Record<FaixaDeslocamento, number> {
  const contagem: Record<FaixaDeslocamento, number> = { proximo: 0, medio: 0, longo: 0, muito_longo: 0 };
  for (const m of municipios) contagem[m.faixa] += 1;
  return contagem;
}

export function contarPorMeio(municipios: readonly MunicipioDeslocamento[]): Record<MeioDeslocamento, number> {
  const contagem: Record<MeioDeslocamento, number> = { carro: 0, aviao: 0 };
  for (const m of municipios) contagem[m.meio] += 1;
  return contagem;
}

/** Filtra por UF, faixa e meio; o critério ausente não filtra. */
export function filtrarDeslocamento(
  municipios: readonly MunicipioDeslocamento[],
  filtro: FiltroDeslocamento,
): MunicipioDeslocamento[] {
  return municipios.filter(
    (m) =>
      (filtro.uf === undefined || m.uf === filtro.uf) &&
      (filtro.faixa === undefined || m.faixa === filtro.faixa) &&
      (filtro.meio === undefined || m.meio === filtro.meio),
  );
}

/** A faixa que os limites do PDF dão para estas horas de ida e volta (compara em minutos). */
export function faixaPelasHoras(horasIdaVolta: number): FaixaDeslocamento {
  const minutos = Math.round(horasIdaVolta * 60);
  const faixa = FAIXAS_DESLOCAMENTO.find((f) => f.ate_horas === null || minutos <= f.ate_horas * 60);
  return faixa?.faixa ?? 'muito_longo';
}

